// Regenerate src/tools.snapshot.ts from a saved remote tools/list response.
//
//   curl -s https://aithon.tech/mcp -H 'content-type: application/json' \
//     -H 'accept: application/json, text/event-stream' \
//     -d '{"jsonrpc":"2.0","id":1,"method":"tools/list"}' > tools.json
//   node scripts/update-snapshot.mjs tools.json
//
// Accepts either a full JSON-RPC response ({ result: { tools } }) or a bare { tools } object.
import { readFileSync, writeFileSync } from 'node:fs';

const input = process.argv[2];
if (!input) {
  console.error('usage: node scripts/update-snapshot.mjs <tools-list.json>');
  process.exit(1);
}

const parsed = JSON.parse(readFileSync(input, 'utf8'));
const tools = (parsed.result ?? parsed).tools;
if (!Array.isArray(tools) || tools.length === 0) {
  console.error(`${input} does not contain a non-empty tools array`);
  process.exit(1);
}

const KEEP = ['name', 'title', 'description', 'inputSchema', 'outputSchema', 'annotations'];
const cleaned = tools.map((tool) => Object.fromEntries(KEEP.filter((k) => tool[k] !== undefined).map((k) => [k, tool[k]])));

const out = `/**
 * Bundled copy of the remote tools/list, served only when the live list
 * cannot be fetched. Generated by scripts/update-snapshot.mjs; do not edit by hand.
 */

import type { RemoteTool } from './tools.js';

export const SNAPSHOT_TOOLS: RemoteTool[] = ${JSON.stringify(cleaned, null, 2)};
`;

writeFileSync(new URL('../src/tools.snapshot.ts', import.meta.url), out);
console.log(`wrote ${cleaned.length} tools to src/tools.snapshot.ts`);
